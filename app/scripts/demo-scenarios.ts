// Runs the scheduler (no AI) for demo scenarios and writes scripts/demo-report.md: npm run demo:scenarios
import { buildSchedules, getNextSchedule, meetingLines, normCode, Schedule, SchedulerInput } from "../src/logic/scheduler";
import { courseSwapIdeas, courseSwapLine } from "../src/logic/advisor";
import { formatTime } from "../src/data/schedule";

declare const require: (name: string) => any; // Node globals (no @types/node in this project)
declare const process: { cwd: () => string };
const fs = require("fs");
const path = require("path");

type Scenario = { name: string; input: SchedulerInput };

const SENIOR_TAKEN = ["CSE 1321", "CSE 1322", "CSE 2300", "CS 3305", "CS 3410", "CS 3502", "CS 3503", "MATH 1190", "MATH 2202", "ENGL 1101", "ENGL 1102"];
const JUNIOR_TAKEN = ["CSE 1321", "CSE 1322", "MATH 1190", "ENGL 1101", "ENGL 1102"];

function make(year: string, taken: string[], selected: string[], numCourses: number, days: string[], times: string[], numOnline: number, busyTimes: { days: string[]; start: number; end: number }[], campus = "Marietta"): SchedulerInput {
  return {
    major: "Computer Science",
    year: year as SchedulerInput["year"],
    campus: campus as SchedulerInput["campus"],
    takenCourses: taken,
    selectedCourses: selected,
    preferences: { numCourses, days, times, numOnline, notes: "", busyTimes } as SchedulerInput["preferences"],
    aiRules: null,
  };
}

const MTWT = ["Mon", "Tue", "Wed", "Thu"];
const seniorA = make("Senior", SENIOR_TAKEN, ["AI 4732", "CS 4722", "CS 4306", "AI 3642"], 4, MTWT, ["Afternoon"], 1, [{ days: ["Mon"], start: 8 * 60, end: 12 * 60 }]);
const juniorC = make("Junior", [...JUNIOR_TAKEN], ["CS 3305", "CSE 2300", "CS 3503", "AI 3642"], 5, MTWT, ["Morning", "Afternoon"], 1, [{ days: ["Fri"], start: 13 * 60, end: 18 * 60 }]);

const scenarios: Scenario[] = [
  { name: "A. Senior, 4 courses, Afternoon, busy Mon 8-12", input: seniorA },
  { name: "B. Senior (11 taken), CS 4308, CS 4504, AI 3642, CS 3622", input: make("Senior", SENIOR_TAKEN, ["CS 4308", "CS 4504", "AI 3642", "CS 3622"], 4, MTWT, ["Afternoon"], 1, []) },
  { name: "C. Junior, 5 courses, Morning + Afternoon, busy Fri 1-6 PM", input: juniorC },
  { name: "D. Junior like C, 0 online, Tue/Thu only", input: { ...juniorC, preferences: { ...juniorC.preferences, numOnline: 0, days: ["Tue", "Thu"] } } },
  { name: "E. Sophomore, 4 courses, Mon-Fri, Anytime, 2 online", input: make("Sophomore", ["CSE 1321", "MATH 1190", "ENGL 1101"], ["CSE 1322", "MATH 2202", "ENGL 1102", "CSE 2300"], 4, ["Mon", "Tue", "Wed", "Thu", "Fri"], ["Anytime"], 2, []) },
  { name: "F. Freshman, nothing taken, 4 courses, Morning, 0 online", input: make("Freshman", [], ["CSE 1321", "MATH 1190", "ENGL 1101"], 4, MTWT, ["Morning"], 0, []) },
  { name: "G. Senior like A, campus Kennesaw", input: { ...seniorA, campus: "Kennesaw" } },
];

const strategyNames = { best: "Best Schedule", professors: "Best Professors", fewestDays: "Fewest Days" };
const stars = (r: number | null) => (r === null ? "no ratings yet" : `${r}★`);
const problems: string[] = [];
const out: string[] = ["# Demo scenario report", "", "Generated by `scripts/demo-scenarios.ts` (scheduler only, no AI).", ""];

function printSchedule(sc: string, title: string, s: Schedule, input: SchedulerInput) {
  out.push(`### ${title}`, "", `- Highlight: ${s.highlight}`, `- Avg rating: ${s.avgRating}★ · Days on campus: ${s.daysOnCampus} · Courses: ${s.items.length}`);
  if (s.badges.length) out.push(`- Badges: ${s.badges.join(" | ")}`);
  if (s.onlineNote) out.push(`- ${s.onlineNote}`);
  out.push("");
  const days = input.preferences.days;
  const taken = new Set(input.takenCourses.map(normCode));
  const seen = new Set<string>();
  for (const item of s.items) {
    const tags = [item.waitlist ? "WAITLIST" : "", item.suggested ? `Suggested (${item.suggestedReason})` : "", item.online ? "Online" : "", ...item.tags].filter(Boolean);
    out.push(`- **${item.code}** ${item.title} — ${item.professor} (${stars(item.rating)}) ${tags.map((t) => `[${t}]`).join(" ")}`);
    for (const line of meetingLines(item)) out.push(`  - ${line}`);
    if (item.alternative) {
      const a = item.alternative;
      out.push(`  - Upgrade your professor (${a.reason}): ${a.item.professor} (${stars(a.item.rating)}) ${meetingLines(a.item).join(" | ")}`);
      if (a.item.rating === null || item.rating === null ? a.item.rating !== null && false : a.item.rating - item.rating < 0.8 - 1e-9) problems.push(`${sc} / ${title}: upgrade for ${item.code} is less than 0.8★ higher`);
    }
    // checks
    if (item.waitlist) problems.push(`${sc} / ${title}: full section in tab (${item.code})`);
    const badDays = [...new Set(item.blocks.filter((b) => !days.includes(b.day)).map((b) => b.day))];
    if (badDays.length) problems.push(`${sc} / ${title}: ${item.code} meets on non-picked day(s) ${badDays.join(", ")}`);
    if (taken.has(normCode(item.code))) problems.push(`${sc} / ${title}: ${item.code} was already taken`);
    if (seen.has(item.code)) problems.push(`${sc} / ${title}: duplicate course ${item.code}`);
    seen.add(item.code);
    if ((item.rating === null) !== item.tags.includes("noRatings")) problems.push(`${sc} / ${title}: noRatings tag doesn't match rating for ${item.code}`);
    for (const b of item.blocks) {
      for (const bt of input.preferences.busyTimes) {
        if (bt.days.includes(b.day) && b.start < bt.end && bt.start < b.end) problems.push(`${sc} / ${title}: ${item.code} overlaps busy time on ${b.day} (${formatTime(b.start)})`);
      }
    }
  }
  const online = s.items.filter((i) => i.online).length;
  if (online > input.preferences.numOnline) problems.push(`${sc} / ${title}: ${online} online classes, limit ${input.preferences.numOnline}`);
  if (s.items.length < input.preferences.numCourses && !input.selectedCourses.every((c) => s.items.some((i) => i.code === c))) {
    // not necessarily wrong (a course may not fit), noted in "Notes"
  }
  out.push("");
  out.push("**Waitlist options**", "");
  if (!s.waitlistOptions.length) out.push("- none");
  for (const o of s.waitlistOptions) out.push(`- ${o.item.code} ${o.item.professor} (${stars(o.item.rating)}) ${meetingLines(o.item).join(" | ")} — ${o.item.waitCount}/${o.item.lecture.waitCapacity} on waitlist`);
  out.push("", "**Swap the course ideas**", "");
  const ideas = courseSwapIdeas(input, s);
  if (!ideas.length) out.push("- none");
  for (const idea of ideas) {
    out.push(`- ${courseSwapLine(idea)} (${meetingLines(idea.item).join(" | ")})`);
    if (idea.item.waitlist) problems.push(`${sc} / ${title}: swap idea ${idea.item.code} is a waitlist section`);
    if (idea.gain < 1.0 - 1e-9) problems.push(`${sc} / ${title}: swap idea ${idea.item.code} gain ${idea.gain} < 1.0`);
    if (taken.has(normCode(idea.item.code))) problems.push(`${sc} / ${title}: swap idea ${idea.item.code} was already taken`);
  }
  out.push("");
}

for (const { name, input } of scenarios) {
  const p = input.preferences;
  out.push(`## ${name}`, "", "**Inputs**", "",
    `- ${input.year} ${input.major}, ${input.campus}, Spring 2027`,
    `- Taken: ${input.takenCourses.join(", ") || "(none)"}`,
    `- Selected: ${input.selectedCourses.join(", ")}`,
    `- ${p.numCourses} courses · days ${p.days.join("/")} · times ${p.times.join("/")} · ${p.numOnline} online`,
    `- Busy: ${p.busyTimes.map((b) => `${b.days.join("/")} ${formatTime(b.start)}-${formatTime(b.end)}`).join("; ") || "(none)"}`, "");
  const result = buildSchedules(input);
  const shown = [...result.schedules];
  for (const s of result.schedules) printSchedule(name, s.strategy ? strategyNames[s.strategy] : "Option", s, input);
  const next = getNextSchedule(input, shown);
  if (next) printSchedule(name, "Find another", next, input);
  else out.push("### Find another", "", "- No more options", "");
  out.push("**Notes**", "");
  if (!result.notes.length) out.push("- none");
  for (const n of result.notes) out.push(`- ${n}`);
  out.push("");

  // badges must match the data
  const all = result.schedules;
  for (const s of all) {
    if (s.badges.some((b) => b.includes("highest-rated")) && s.avgRating < Math.max(...all.map((x) => x.avgRating)) - 1e-9) problems.push(`${name}: "highest-rated" badge but avg ${s.avgRating} isn't the top`);
    if (s.badges.some((b) => b.includes("fewest days")) && s.daysOnCampus > Math.min(...all.map((x) => x.daysOnCampus))) problems.push(`${name}: "fewest days" badge but ${s.daysOnCampus} days isn't the lowest`);
  }
  if (!all.length) problems.push(`${name}: no schedules produced`);
}

out.push("## Looks wrong", "");
const unique = [...new Set(problems)];
if (!unique.length) out.push("- nothing found");
for (const x of unique) out.push(`- ${x}`);
out.push("");

fs.writeFileSync(path.join(process.cwd(), "scripts", "demo-report.md"), out.join("\n"));
console.log(`${scenarios.length} scenarios ran, ${unique.length} looks-wrong items`);
